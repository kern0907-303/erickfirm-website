export function legalDocumentText(document) {
  const values = [document.title, document.lastUpdated, document.intro];
  for (const section of document.sections) {
    values.push(section.title);
    for (const block of section.blocks) {
      if (block.type === 'p') values.push(block.text);
      if (block.type === 'ul') values.push(...block.items);
      if (block.type === 'card') {
        values.push(block.entity + ' / 統一編號 ' + block.taxId + ' / ' + block.email + ' / ' + block.lineLabel);
      }
    }
  }
  return values;
}
