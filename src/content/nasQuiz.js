// 計分：次數最多的類型；同分看第 8 題，第 8 題分不出來再看第 1 題。
// 後端 src/lib/nas-quiz.mjs 有一模一樣的規則，改這裡要同步改那裡。
export function scoreQuiz(answers) {
  const counts = { L: 0, D: 0, O: 0, K: 0, M: 0 };
  answers.forEach((code) => { if (code in counts) counts[code] += 1; });
  const max = Math.max(...Object.values(counts));
  const tied = Object.keys(counts).filter((code) => counts[code] === max);
  if (tied.length === 1) return tied[0];
  if (tied.includes(answers[7])) return answers[7];
  if (tied.includes(answers[0])) return answers[0];
  return tied[0];
}

